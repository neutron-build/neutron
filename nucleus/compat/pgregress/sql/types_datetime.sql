-- date/timestamp arithmetic and formatting
SELECT DATE '2024-02-29';
SELECT DATE '2023-02-29';
SELECT DATE '2024-01-31' + 1;
SELECT DATE '2024-03-01' - DATE '2024-02-01';
SELECT TIMESTAMP '2024-01-01 12:30:45';
SELECT TIMESTAMP '2024-01-01 12:30:45' + INTERVAL '1 day';
SELECT TIMESTAMP '2024-01-01 12:30:45' + INTERVAL '90 minutes';
SELECT TIMESTAMP '2024-03-31 00:00:00' + INTERVAL '1 month';
SELECT TIMESTAMP '2024-01-31 00:00:00' + INTERVAL '1 month';
SELECT INTERVAL '1 day' + INTERVAL '2 hours';
SELECT EXTRACT(YEAR FROM DATE '2024-06-15'), EXTRACT(MONTH FROM DATE '2024-06-15'), EXTRACT(DAY FROM DATE '2024-06-15');
SELECT EXTRACT(HOUR FROM TIMESTAMP '2024-01-01 23:45:00'), EXTRACT(MINUTE FROM TIMESTAMP '2024-01-01 23:45:00');
SELECT EXTRACT(DOW FROM DATE '2024-06-16'), EXTRACT(DOY FROM DATE '2024-02-01');
SELECT EXTRACT(EPOCH FROM TIMESTAMP '1970-01-01 00:00:10');
SELECT date_trunc('month', TIMESTAMP '2024-06-15 12:34:56');
SELECT date_trunc('hour', TIMESTAMP '2024-06-15 12:34:56');
SELECT DATE '2024-01-01' < DATE '2024-06-01', TIMESTAMP '2024-01-01 00:00:00' = DATE '2024-01-01';
CREATE TABLE rd (d DATE, t TIMESTAMP);
INSERT INTO rd VALUES ('2024-01-15', '2024-01-15 10:00:00'), ('2023-12-31', '2023-12-31 23:59:59');
SELECT d, t FROM rd ORDER BY d;
SELECT d FROM rd WHERE d BETWEEN '2024-01-01' AND '2024-12-31' ORDER BY d;
SELECT MIN(d), MAX(t) FROM rd;
SELECT d + INTERVAL '1 year' FROM rd ORDER BY d;
DROP TABLE rd;
