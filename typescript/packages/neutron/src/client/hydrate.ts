interface RouteModule {
  id?: string;
  path?: string;
  parentId?: string | null;
  default: ComponentType<{ data?: unknown; params?: Record<string, string>; actionData?: unknown }>;
  loader?: () => Promise<unknown>;
  ErrorBoundary?: ComponentType<{ error: Error; reset?: () => void }>;
}

interface RouteRegistration {
  id?: string;
  path?: string;
  parentId?: string | null;
  isLayout?: boolean;
  isNotFound?: boolean;
  mode?: "static" | "app";
  hasLoader?: boolean;
  load?: () => Promise<unknown>;
  /** `false` for a static-tier route: the build ships no client module for it. */
  clientModule?: false;
  default?: ComponentType<{ data?: unknown; params?: Record<string, string>; actionData?: unknown }>;
  loader?: () => Promise<unknown>;
  ErrorBoundary?: ComponentType<{ error: Error; reset?: () => void }>;
}

interface RouteInfo {
  id: string;
  path: string;
  module: RouteModule | null;
  load: () => Promise<RouteModule>;
  parentId: string | null;
  isLayout: boolean;
  /**
   * A `not-found.tsx` carries its DIRECTORY's path, so on the client it is
   * indistinguishable by path from that directory's index route. The server
   * trie keeps it out for the same reason (see core/router.ts); this router
   * must skip it too, or a 404 page shadows the page it was meant to cover.
   * Older route tables omit the flag, which reads as false — the previous
   * behaviour.
   */
  isNotFound: boolean;
  /**
   * Emitted into the route table by the build. The client cannot derive
   * either: `mode` lives in server-side route config, and `loader` is stripped
   * from the client bundle, so every route would otherwise look loader-free.
   *
   * Both are optional because a route table generated by an older build will
   * not carry them. Absent means unknown, and unknown must resolve to the
   * conservative answer — fetch — never to a skipped request.
   */
  mode?: "static" | "app";
  hasLoader?: boolean;
  /** No client module: the route renders at the static tier (staticTierRouteIds). */
  clientModule?: false;
}

