// ── CSS loading for SPA navigation ──
const loadedStylesheets = new Set<string>();
const CSS_LOAD_TIMEOUT_MS = 5000;
// Every route stylesheet the build named (a route's `__css__` list, or its
// `__cssLazy__` one: CSS its dynamic imports bring in). A link with one of
// these hrefs is a route stylesheet however it got into the document —
// linked by the server or the router (`data-neutron-css`), or by Vite's
// preload helper when a route chunk or a lazy module loaded, which marks
// nothing. Only these are ever unlinked (client.unloadRouteStylesheets).
const routeStylesheets = new Set<string>();
// Route stylesheets this router unlinked. Vite's preload helper inserts a
// sheet once per href and never again, so a lazy module loaded before keeps
// importing without its CSS: the router relinks these itself.
const unlinkedStylesheets = new Set<string>();

function initLoadedStylesheets(): void {
  document.querySelectorAll<HTMLLinkElement>('link[rel="stylesheet"]').forEach((link) => {
    if (link.href) {
      try {
        // Normalize to pathname for stable comparison across dev query params
        loadedStylesheets.add(new URL(link.href).pathname);
      } catch {
        loadedStylesheets.add(link.href);
      }
    }
    if (link.hasAttribute("data-neutron-css")) {
      routeStylesheets.add(normalizeStylesheetUrl(link.getAttribute("href") || link.href));
    }
  });
  // The first page's lazy CSS, named on the client entry's script tag.
  const lazy = document.querySelector("script[data-neutron-css-lazy]")?.getAttribute("data-neutron-css-lazy");
  for (const href of lazy ? lazy.split(" ").filter(Boolean) : []) {
    routeStylesheets.add(normalizeStylesheetUrl(href));
  }
}

function normalizeStylesheetUrl(url: string): string {
  try {
    return new URL(url, window.location.origin).pathname;
  } catch {
    return url;
  }
}

function linkedStylesheets(key: string): HTMLLinkElement[] {
  return Array.from(document.querySelectorAll<HTMLLinkElement>('link[rel="stylesheet"]')).filter(
    (link) => normalizeStylesheetUrl(link.getAttribute("href") || link.href) === key
  );
}

async function loadMissingStylesheets(urls: string[]): Promise<void> {
  const missing = urls.filter((url) => {
    const key = normalizeStylesheetUrl(url);
    // Vite's preload helper may have linked it already (the route chunk's CSS,
    // loaded with the chunk): adopt that link rather than add a second one
    // that unloading would remove while the first stays.
    const existing = linkedStylesheets(key);
    for (const link of existing) link.setAttribute("data-neutron-css", "");
    return existing.length === 0;
  });
  if (missing.length === 0) return;

  await Promise.race([
    Promise.all(
      missing.map(
        (url) =>
          new Promise<void>((resolve) => {
            const link = document.createElement("link");
            link.rel = "stylesheet";
            link.href = url;
            link.setAttribute("data-neutron-nav", "true");
            link.setAttribute("data-neutron-css", "");
            link.onload = () => {
              loadedStylesheets.add(normalizeStylesheetUrl(url));
              resolve();
            };
            link.onerror = () => {
              // Don't block navigation on CSS error
              resolve();
            };
            document.head.appendChild(link);
            unlinkedStylesheets.delete(normalizeStylesheetUrl(url));
          })
      )
    ),
    // Safety valve: full-page reload if CSS takes too long
    new Promise<void>((_, reject) =>
      setTimeout(() => reject(new Error("css-timeout")), CSS_LOAD_TIMEOUT_MS)
    ),
  ]);
}

/**
 * The stylesheets to link before a route renders: its own list, plus the
 * lazy CSS of its dynamic imports that this router unlinked earlier (Vite
 * will not link those again). Records both lists as route stylesheets.
 */
function routeStylesheetsToLoad(css: string[], lazy: string[]): string[] {
  for (const href of [...css, ...lazy]) routeStylesheets.add(normalizeStylesheetUrl(href));
  if (!routerOptions.unloadRouteStylesheets) return css;
  return [...css, ...lazy.filter((href) => unlinkedStylesheets.has(normalizeStylesheetUrl(href)))];
}

function readLazyStylesheets(data: Record<string, unknown>): string[] {
  const lazy = data.__cssLazy__;
  delete data.__cssLazy__;
  return Array.isArray(lazy) ? (lazy as string[]) : [];
}

/**
 * With `client.unloadRouteStylesheets`: once the page navigated to has
 * rendered (the next frame), unlink the route stylesheets it uses through
 * neither path — not in its list (`__css__`), not CSS its dynamic imports
 * can bring in (`__cssLazy__`). A route stylesheet is recognised by its href
 * (see `routeStylesheets`), so the links Vite's preload helper inserts go
 * too; every other link (a `head()` stylesheet, a third-party sheet) stays.
 * The client entry's and layouts' stylesheets are in every route's list.
 * Unlinking after the render means the outgoing page never loses its styles
 * while it is still on screen, and the incoming page's were loaded before it
 * rendered (loadMissingStylesheets).
 */
function unloadUnusedStylesheets(keep: string[], requestId: number): void {
  if (!routerOptions.unloadRouteStylesheets) return;
  const wanted = new Set(keep.map(normalizeStylesheetUrl));
  const run = () => {
    // A later navigation owns the document now; it will unload for itself.
    if (requestId !== latestNavigationRequestId) return;
    document.querySelectorAll<HTMLLinkElement>('link[rel="stylesheet"]').forEach((link) => {
      const key = normalizeStylesheetUrl(link.getAttribute("href") || link.href);
      if (wanted.has(key)) return;
      if (!link.hasAttribute("data-neutron-css") && !routeStylesheets.has(key)) return;
      link.remove();
      loadedStylesheets.delete(key);
      unlinkedStylesheets.add(key);
    });
  };
  if (typeof requestAnimationFrame === "function") {
    requestAnimationFrame(() => run());
  } else {
    setTimeout(run, 0);
  }
}

/**
 * Start the router. Resolves `"static"` without starting it when the current
 * page is a static-tier route the build shipped no client module for.
 */
export async function init(): Promise<"static" | void> {
  if (initialized) return;
  initialized = true;

  if (import.meta.env.DEV) {
    await import("preact/debug");
  }

  // A static-tier page (its whole chain renders without the router) has no
  // client module to hydrate it with: the router does not start, and the
  // caller boots the document as a static page — islands only, as a
  // prerendered page that never loads this module would be.
  const initialRoute = renderedNotFoundRoute() ?? findRoute(getCurrentPath());
  if (initialRoute && [...getLayoutChain(initialRoute), initialRoute].some((r) => r.clientModule === false)) {
    initialized = false;
    return "static";
  }

  window.__NEUTRON_ROUTER_ACTIVE__ = true;
  initLoadedStylesheets();
  snapshotHeadTags();

  const data = readInitialLoaderData();
  const pathname = getCurrentPath();
  currentUrl = pathname + getCurrentSearch();
  
  const route = initialRoute;
  if (!route) {
    console.warn("No route found for", pathname);
    return;
  }
  
  currentRoute = route;
  layouts = getLayoutChain(route);
  await ensureRouteChainModules([...layouts, route]);
  
  hydrateApp(data);
  markStaticLinks();
  setNavigationState({ state: "idle" });

  window.addEventListener("neutron:data-updated", (event: Event) => {
    const data = (event as CustomEvent<LoaderData>).detail;
    if (!data) return;

    void handleIncomingDataUpdate(data);
  });
  
  subscribeNavigationStart(() => {
    activeNavigationController?.abort();
    activeNavigationController = null;
    latestNavigationRequestId++;
  });
  subscribe((event) => {
    return handleNavigation(event.forceRevalidate === true, event.generation);
  });

  // Warm navigations before the click lands. This is what makes a same-origin
  // navigation cost zero network: `handleNavigation` reads the cache this
  // fills. Nothing imported this module before, so it had never run.
  setupIncrementalPrefetch();

  // Global click interceptor — makes all same-origin <a> tags do SPA navigation.
  // Without this, only <Link> components would trigger SPA nav; raw <a> tags
  // would cause full page reloads (white flash, lost JS state).
  document.addEventListener("click", (event: MouseEvent) => {
    if (event.defaultPrevented) return;
    if (event.button !== 0) return;
    if (event.metaKey || event.altKey || event.ctrlKey || event.shiftKey) return;

    const target = event.target;
    const anchor = target instanceof Element ? target.closest("a") : null;
    if (!anchor) return;
    if (anchor.target && anchor.target !== "_self") return;
    if (anchor.hasAttribute("download")) return;
    if (anchor.origin !== window.location.origin) return;

    // Same-page hash link (e.g. #work, or /current#section): let the browser
    // scroll to the target natively instead of swallowing the hash. Without
    // this early return the interceptor strips the hash and re-navigates
    // hash-less, so in-page anchors never scroll.
    if (
      anchor.hash &&
      anchor.pathname === window.location.pathname &&
      anchor.search === window.location.search
    ) {
      return;
    }

    // A static target is left to the browser. Intercepting it bought nothing:
    // the fetch returned head and CSS for a page whose component was already
    // in the bundle, and the prerender the speculation rules started on hover
    // has the real document painted already. Not calling preventDefault is
    // also what lets the browser ACTIVATE that prerender.
    if (isBrowserNavigationTarget(anchor.pathname)) {
      return;
    }

    // Keep the hash so navigate() can preserve it and scroll on arrival for
    // cross-page anchor links (e.g. /about#team).
    const href = anchor.pathname + anchor.search + anchor.hash;
    event.preventDefault();
    navigate(href as RouteHref);
  });
}

async function handleIncomingDataUpdate(data: LoaderData): Promise<void> {
  const nextUrl = getCurrentPath() + getCurrentSearch();
  const identity = getNavigationGeneration();
  const requestId = latestNavigationRequestId;
  // Submit/revalidate data belongs to the committed document. A pending
  // destination may need a different layout chain and complete loader diff.
  if (nextUrl !== currentUrl || !currentRoute) return;
  await ensureRouteChainModules([...layouts, currentRoute]);
  if (identity !== getNavigationGeneration() || requestId !== latestNavigationRequestId || nextUrl !== currentUrl) return;
  applyData(data);
}

/**
 * The not-found route the server rendered this document with (F-P6-5), named
 * on the client entry's script tag (`data-neutron-not-found`). The URL alone
 * cannot say: after a page or layout loader's `notFound()`, or a static
 * route's ungenerated param, it still matches the page — which `findRoute`
 * would hydrate without its data, over the 404 markup. Only the first
 * document carries it; client navigation matches by URL.
 */
function renderedNotFoundRoute(): RouteInfo | null {
  const id = document.querySelector("script[data-neutron-not-found]")?.getAttribute("data-neutron-not-found");
  if (!id) return null;
  return routes.find((route) => route.id === id && route.isNotFound) ?? null;
}

function findRoute(pathname: string): RouteInfo | null {
  for (const route of [...routes].sort((a, b) => comparePathSpecificity(a.path, b.path))) {
    if (route.isLayout || route.isNotFound) continue;
    if (matchPath(route.path, pathname)) {
      return route;
    }
  }
  return null;
}

/**
 * Whether a same-origin path resolves to a route this router should NOT handle.
 *
 * A `mode: "static"` route is prerendered and served from `dist/` without
 * middleware (`server/index.ts` returns the cached HTML before
 * `renderAppRoute` runs, and global middleware is only invoked inside it), so
 * a browser navigation to one is both correct and cheaper than a client
 * render: the document is already painted by the time the click lands, because
 * the speculation rules this tier emits prerender it.
 *
 * Unknown resolves to false — handle it in the router — so an older route
 * table never silently turns SPA navigation into full page loads.
 */
function isBrowserNavigationTarget(pathname: string): boolean {
  const route = findRoute(pathname);
  if (!route) return false;
  const chain = [...getLayoutChain(route), route];
  // Built without a client module: only a document load can render it.
  if (chain.some((entry) => entry.clientModule === false)) return true;
  if (route.mode !== "static") return false;
  return getLayoutChain(route).every((layout) => layout.mode === "static");
}

/**
 * Tag anchors whose target is a static route.
 *
 * The speculation rules emitted for an app-tier document are scoped to this
 * attribute, which is what keeps the browser from prerendering app routes and
 * running their loaders and middleware for pages nobody asked for.
 */
function markStaticLinks(): void {
  document.querySelectorAll<HTMLAnchorElement>("a[href]").forEach((anchor) => {
    if (anchor.origin !== window.location.origin) return;
    if (isBrowserNavigationTarget(anchor.pathname)) {
      anchor.setAttribute("data-neutron-static", "");
    } else {
      anchor.removeAttribute("data-neutron-static");
    }
  });
}

function matchPath(pattern: string, pathname: string): boolean {
  try { return bindPathParams(pattern, parseUrlPath(decodeURIComponent(pathname))) !== null; } catch { return false; }
}

function getLayoutChain(route: RouteInfo): RouteInfo[] {
  const chain: RouteInfo[] = [];
  let currentId: string | null = route.parentId;
  
  while (currentId) {
    const layout = routes.find((r) => r.id === currentId);
    if (layout) {
      chain.unshift(layout);
      currentId = layout.parentId;
    } else {
      break;
    }
  }
  
  return chain;
}

function hydrateApp(data: LoaderData) {
  if (!currentRoute) return;
  
  const pathname = getCurrentPath();
  const search = getCurrentSearch();
  const params = routeParams(currentRoute, pathname);
  
  const actionData = data.__action__;
  const loaderData = { ...data };
  delete loaderData.__action__;
  
  // Build the element tree
  const allRoutes = [...layouts, currentRoute];
  window.__NEUTRON_ACTIVE_ROUTE_IDS__ = allRoutes.map((route) => route.id);

  interface RouteElement {
    Component: ComponentType;
    data: unknown;
    params: Record<string, string>;
    ErrorBoundary?: ComponentType<{ error: Error; reset?: () => void }>;
  }

  const elements: RouteElement[] = [];

  for (const r of allRoutes) {
    if (!r.module) {
      return;
    }
    const routeData = loaderData[r.id];
    elements.push({
      Component: r.module.default,
      data: routeData,
      params,
      ErrorBoundary: r.module.ErrorBoundary,
    });
  }

  // Build nested element with per-route error boundaries
  let element: preact.VNode | null = null;

  for (let i = elements.length - 1; i >= 0; i--) {
    const { Component, data: routeData, params: routeParams, ErrorBoundary } = elements[i];

    if (element === null) {
      element = h(Component, { data: routeData, params: routeParams, actionData } as preact.ComponentProps<typeof Component>);
    } else {
      element = h(Component, { data: routeData } as preact.ComponentProps<typeof Component>, element);
    }

    // Wrap with route's ErrorBoundary if exported
    if (ErrorBoundary) {
      element = h(ClientErrorBoundary, { fallback: ErrorBoundary }, element);
    }
  }

  if (!element) return;

  // Root-level error boundary catches anything not caught by route boundaries
  element = h(ClientErrorBoundary, null, element);

  // Wrap with contexts
  const app = h(
    RouterContext.Provider,
    { value: { routeId: currentRoute.id, pathname, search, params } },
    h(
      LoaderContext.Provider,
      { value: loaderData },
      h(
        ActionDataContext.Provider,
        { value: actionData },
        h(
          NavigationContext.Provider,
          { value: { state: "idle" } },
          element
        )
      )
    )
  );
  
  const appElement = document.getElementById("app");
  if (appElement) {
    try {
      if (!hydrated) {
        hydrate(app, appElement);
        hydrated = true;
      } else {
        render(app, appElement);
      }
    } catch (err) {
      console.error("[neutron] Hydration failed, keeping SSR HTML:", err);
      // Don't dispatch neutron:hydrated — the init style stays in place
      // and the SSR HTML remains intact.
      return;
    }
    // <Island> renders `h("neutron-island", …, h(Component, props))`, so the
    // full-tree hydrate above ALREADY mounted every island component inside
    // the app root. Letting initIslands() hydrate them again creates a second
    // Preact root over the same container: the static markup matches on both
    // passes so nothing visibly duplicates at first, but each root then
    // inserts its own dynamic nodes — a percentage rendered twice ("16%%"),
    // two progress bars, two copies of a conditional list. Claim them for the
    // app root so the island runtime only handles markers the router doesn't
    // own (SSR-only pages, or islands mounted outside #app).
    appElement.querySelectorAll<HTMLElement & { __neutronHydrated?: boolean }>(
      "neutron-island"
    ).forEach((island) => {
      island.__neutronHydrated = true;
    });

    initIslands();

    // Notify ScrollReveal (and other components) that hydration is complete.
    // New DOM nodes may have been created — they need reveal processing.
    document.dispatchEvent(new CustomEvent("neutron:hydrated"));
  }
}

function applyData(data: LoaderData): void {
  const decoded = decodeLoaderDataPayload(data);

  // Extract and apply head HTML if present (from SPA navigation JSON response)
  const headHtml = (decoded as Record<string, unknown>).__head__;
  if (typeof headHtml === "string") {
    applyHeadHtml(headHtml);
    delete (decoded as Record<string, unknown>).__head__;
  }

  window.__NEUTRON_DATA__ = decoded;
  hydrateApp(decoded);
  // The page that just rendered brings its own links; an observer that only
  // ever saw the first page's DOM would warm nothing after the first
  // navigation. Cheap: already-observed nodes are skipped.
  observeVisibleLinks();
  markStaticLinks();
}

// The head tags client navigation manages: the server-rendered document's
// <meta> (name / property / http-equiv) and <link> (not stylesheets or
// preloads) tags, and the ones navigation inserted since. Tags other code
// adds at runtime are never touched.
const managedHeadTags = new Set<Element>();

function isManagedHeadTag(element: Element): boolean {
  const tag = element.tagName.toLowerCase();
  if (tag === "meta") {
    return (
      !element.hasAttribute("charset") &&
      (element.hasAttribute("name") || element.hasAttribute("property") || element.hasAttribute("http-equiv"))
    );
  }
  if (tag === "link") {
    const rel = (element.getAttribute("rel") || "").toLowerCase().split(/\s+/);
    return !rel.includes("stylesheet") && !rel.includes("modulepreload") && !rel.includes("preload");
  }
  return false;
}

function snapshotHeadTags(): void {
  document.head.querySelectorAll("meta, link").forEach((element) => {
    if (isManagedHeadTag(element)) managedHeadTags.add(element);
  });
}

function headTagSignature(element: Element): string {
  const attrs = Array.from(element.attributes)
    .map((attr) => `${attr.name.toLowerCase()}=${attr.value}`)
    .sort();
  return `${element.tagName.toLowerCase()} ${JSON.stringify(attrs)}`;
}

/**
 * Apply server-rendered head HTML (`__head__`, the page's whole resolved
 * head) to the live document: the title, and every managed <meta>/<link> —
 * a tag the new head no longer has is removed, one it adds is inserted,
 * identical ones stay. The HTML is parsed inertly (a <template>), and only
 * attributes are copied onto fresh elements, never event handlers.
 */
function applyHeadHtml(headHtml: string): void {
  const template = document.createElement("template");
  template.innerHTML = headHtml;
  const title = template.content.querySelector("title");
  if (title) {
    document.title = title.textContent ?? "";
  }

  const incoming = new Map<string, Element>();
  template.content.querySelectorAll("meta, link").forEach((element) => {
    if (isManagedHeadTag(element)) incoming.set(headTagSignature(element), element);
  });
  for (const element of [...managedHeadTags]) {
    const signature = headTagSignature(element);
    if (element.isConnected && incoming.has(signature)) {
      incoming.delete(signature);
      continue;
    }
    element.remove();
    managedHeadTags.delete(element);
  }
  for (const source of incoming.values()) {
    const element = document.createElement(source.tagName.toLowerCase());
    for (const attr of Array.from(source.attributes)) {
      if (/^on/i.test(attr.name)) continue;
      element.setAttribute(attr.name, attr.value);
    }
    document.head.appendChild(element);
    managedHeadTags.add(element);
  }
}

function safeDecodeSegment(segment: string | undefined): string {
  if (segment === undefined) return "";
  try {
    return decodeURIComponent(segment);
  } catch {
    return segment;
  }
}

function extractParams(pattern: string, pathname: string, prefix = false): Record<string, string> {
  try { return bindPathParams(pattern, parseUrlPath(decodeURIComponent(pathname)), prefix) ?? {}; } catch { return {}; }
}

/** A not-found route's path is its scope, bound as a prefix (server: findNotFoundMatch). */
function routeParams(route: RouteInfo, pathname: string): Record<string, string> {
  return extractParams(route.path, pathname, route.isNotFound);
}

// Redirects followed in a row by the client router; reset by any navigation
// that lands. Bounded like a browser's own redirect limit.
const MAX_DATA_REDIRECTS = 20;
let consecutiveDataRedirects = 0;

async function handleNavigation(forceRevalidate: boolean = false, navigationIdentity = getNavigationGeneration()) {
  const pathname = getCurrentPath();
  const search = getCurrentSearch();
  const nextUrl = pathname + search;

  if (!forceRevalidate && nextUrl === currentUrl) {
    return;
  }

  activeNavigationController?.abort();
  const controller = new AbortController();
  activeNavigationController = controller;
  const requestId = ++latestNavigationRequestId;
  const isCurrent = () => !controller.signal.aborted && requestId === latestNavigationRequestId && navigationIdentity === getNavigationGeneration() && window.location.pathname + window.location.search === nextUrl;

  const previousUrl = currentUrl;
  const previousPathname = toPathname(previousUrl) || pathname;
  const previousSearch = toSearch(previousUrl);

  const route = findRoute(pathname);
  if (!route) {
    window.location.reload();
    return;
  }

  // Programmatic navigate() and <Link>'s own onClick bypass the interceptor,
  // so the static-target rule is enforced here too. `replace` rather than
  // `assign`: navigate() already pushed this URL, and assigning would leave
  // two history entries for one navigation.
  if (isBrowserNavigationTarget(pathname)) {
    window.location.replace(nextUrl);
    return;
  }

  const previousRoute = currentRoute;
  const previousLayouts = [...layouts];
  const nextLayouts = getLayoutChain(route);

  const previousSnapshots = previousRoute
    ? buildRouteSnapshots([...previousLayouts, previousRoute], previousPathname)
    : [];
  const nextSnapshots = buildRouteSnapshots([...nextLayouts, route], pathname);

  const searchChanged = previousSearch !== search;
  const requestedRouteIds = forceRevalidate || searchChanged
    ? nextSnapshots.map((snapshot) => snapshot.id)
    : diffRequestedRouteIds(previousSnapshots, nextSnapshots);

  // currentRoute/layouts/currentUrl describe the data that actually committed,
  // never a destination whose chunks or loader response are still pending.
  const commit = (data: LoaderData) => {
    if (!isCurrent()) return;
    currentRoute = route;
    layouts = nextLayouts;
    currentUrl = nextUrl;
    applyData(data);
  };
  try {
    await ensureRouteChainModules([...nextLayouts, route]);
    if (!isCurrent()) return;
  } catch (error) {
    // A deploy replaces every hashed chunk and the old ones stop existing, so a
    // tab open across a release asks for a file that is gone and the import
    // rejects. Nothing caught that, so the navigation simply never finished:
    // the click did nothing, forever, with no error the user could act on.
    //
    // A full navigation to the same URL is the recovery — it fetches the new
    // document, which references the chunks that now exist. Deliberately
    // `assign` to the target rather than `reload`, so the user still lands
    // where they clicked instead of being bounced back to the page they left.
    if (typeof console !== "undefined") {
      console.warn("neutron: route chunk failed to load, falling back to a full navigation", error);
    }
    if (isCurrent()) window.location.assign(nextUrl);
    return;
  }

  const prefetched = forceRevalidate ? null : takePrefetch(nextUrl);
  if (prefetched) {
    // CSS should already be loaded from the prefetch, but a route whose
    // stylesheet was evicted or never fetched still must not paint unstyled.
    const prefetchCss = (prefetched as Record<string, unknown>).__css__;
    const prefetchLazyCss = readLazyStylesheets(prefetched as Record<string, unknown>);
    if (Array.isArray(prefetchCss)) {
      try {
        await loadMissingStylesheets(routeStylesheetsToLoad(prefetchCss as string[], prefetchLazyCss));
      } catch {
        // CSS timeout — fall back to full page load (guaranteed no FOUC)
        if (isCurrent()) window.location.href = nextUrl;
        return;
      }
      delete (prefetched as Record<string, unknown>).__css__;
      if (!isCurrent()) {
        return;
      }
    }
    const merged = mergeLoaderData(window.__NEUTRON_DATA__ || {}, prefetched);
    commit(merged);
    if (Array.isArray(prefetchCss)) {
      unloadUnusedStylesheets([...(prefetchCss as string[]), ...prefetchLazyCss], requestId);
    }
    setNavigationState({ state: "idle" });
    if (activeNavigationController === controller) activeNavigationController = null;
    // Same contract as the fetched path: a new page starts at the top. Leaving
    // this out made a warmed navigation land mid-page, so whether scrolling
    // worked depended on whether the link happened to be prefetched.
    if (previousPathname !== pathname) {
      window.scrollTo({ top: 0, left: 0, behavior: "auto" });
    }
    return;
  }

  setNavigationState({
    state: "loading",
    location: nextUrl,
  });

  const requestHeaders: Record<string, string> = {
    Accept: "application/json",
    "X-Neutron-Data": "true",
  };
  if (requestedRouteIds.length > 0) {
    requestHeaders["X-Neutron-Routes"] = requestedRouteIds.join(",");
  }

  try {
    const response = await fetch(pathname + search, {
      headers: requestHeaders,
      signal: controller.signal,
    });

    if (!isCurrent()) {
      return;
    }

    // The URL redirected (loader, middleware or a config rule). Its data is
    // not this URL's, and the redirect target may lose the address bar's
    // query if rendered in place, so navigate to the target instead,
    // replacing the entry that redirected. The route state still describes
    // the page on screen (it changes only at commit), so the target's layout
    // diff is taken against what was rendered.
    const redirectTo = dataRedirectTarget(response);
    if (redirectTo !== null) {
      if (++consecutiveDataRedirects > MAX_DATA_REDIRECTS) {
        // A loop: hand it to the browser, which reports it.
        consecutiveDataRedirects = 0;
        window.location.replace(redirectTo);
        return;
      }
      followDataRedirect(redirectTo, { replace: true });
      return;
    }
    consecutiveDataRedirects = 0;

    if (response.ok) {
      const payload = await response.json();
      if (!isCurrent()) return;
      const data = decodeLoaderDataPayload(payload);

      // Load CSS for the new route before DOM swap
      const cssUrls = (data as Record<string, unknown>).__css__;
      const lazyCssUrls = readLazyStylesheets(data as Record<string, unknown>);
      if (Array.isArray(cssUrls)) {
        try {
          await loadMissingStylesheets(routeStylesheetsToLoad(cssUrls as string[], lazyCssUrls));
        } catch {
          // CSS timeout — fall back to full page load (guaranteed no FOUC)
          if (isCurrent()) window.location.href = nextUrl;
          return;
        }
        delete (data as Record<string, unknown>).__css__;

        // Re-check: another navigation may have started while CSS was loading
        if (!isCurrent()) {
          return;
        }
      }

      const merged = mergeLoaderData(window.__NEUTRON_DATA__ || {}, data);
      commit(merged);
      if (Array.isArray(cssUrls)) {
        unloadUnusedStylesheets([...(cssUrls as string[]), ...lazyCssUrls], requestId);
      }
      if (previousPathname !== pathname) {
        window.scrollTo({ top: 0, left: 0, behavior: "auto" });
      }
    } else {
      window.location.reload();
    }
  } catch (error) {
    if (!isCurrent()) {
      return;
    }
    window.location.reload();
  } finally {
    if (isCurrent()) {
      setNavigationState({ state: "idle" });
      if (activeNavigationController === controller) {
        activeNavigationController = null;
      }
    }
  }
}

interface RouteSnapshot {
  id: string;
  params: Record<string, string>;
}

function buildRouteSnapshots(
  chain: RouteInfo[],
  pathname: string
): RouteSnapshot[] {
  // Server layout loaders receive the full matched leaf params. Comparing
  // layout patterns exactly to a longer URL silently produces empty params.
  const params = chain.length ? routeParams(chain[chain.length - 1], pathname) : {};
  return chain.map(route => ({ id: route.id, params: { ...params } }));
}

function diffRequestedRouteIds(
  previous: RouteSnapshot[],
  next: RouteSnapshot[]
): string[] {
  const previousById = new Map(previous.map((entry) => [entry.id, entry.params]));
  const requested: string[] = [];
  for (const nextEntry of next) {
    const previousParams = previousById.get(nextEntry.id);
    if (!previousParams) {
      requested.push(nextEntry.id);
      continue;
    }
    if (!areParamsEqual(previousParams, nextEntry.params)) {
      requested.push(nextEntry.id);
    }
  }
  return requested;
}

function areParamsEqual(
  left: Record<string, string>,
  right: Record<string, string>
): boolean {
  const leftKeys = Object.keys(left);
  const rightKeys = Object.keys(right);
  if (leftKeys.length !== rightKeys.length) {
    return false;
  }
  for (const key of leftKeys) {
    if (left[key] !== right[key]) {
      return false;
    }
  }
  return true;
}

function mergeLoaderData(existing: LoaderData, incoming: LoaderData): LoaderData {
  const merged: LoaderData = { ...existing };
  delete (merged as Record<string, unknown>).__action__;

  for (const [key, value] of Object.entries(incoming)) {
    merged[key] = value;
  }

  return merged;
}

function toPathname(url: string): string {
  const [pathname] = url.split("?");
  return pathname || "/";
}

function toSearch(url: string): string {
  const index = url.indexOf("?");
  return index >= 0 ? url.slice(index) : "";
}

// Register routes from virtual module
export function registerRoutes(routeMap: Record<string, RouteRegistration | RouteModule>) {
  routes = Object.entries(routeMap as Record<string, RouteRegistration>).map(([id, registration]) => ({
    id,
    path:
      registration.path || id.replace(/^route:/, "").replace(/\.(tsx|ts|jsx|js|mdx)$/, ""),
    module:
      typeof registration.load === "function" || registration.clientModule === false
        ? null
        : normalizeRouteModule(registration),
    load:
      registration.clientModule === false
        ? async () => {
            throw new Error(`neutron: route ${id} renders at the static tier and has no client module`);
          }
        : typeof registration.load === "function"
          ? async () => normalizeRouteModule(await registration.load!())
          : async () => normalizeRouteModule(registration),
    parentId: registration.parentId ?? null,
    isLayout: registration.isLayout === true,
    isNotFound: registration.isNotFound === true,
    mode: registration.mode,
    hasLoader: registration.hasLoader,
    clientModule: registration.clientModule,
  }));
}

/**
 * Whether a navigation to `route` must ask the server.
 *
 * True unless the whole chain is provably static and loader-free. Everything
 * unknown resolves to true: a route table from an older build carries neither
 * field, and guessing "no fetch" there would render a page without its data.
 *
 * Note this answers only "is there server data to collect". It is NOT on its
 * own sufficient to skip the request — the response also carries `__head__`
 * and `__css__`, and it is the only point where server middleware runs during
 * a client navigation. See docs/NEUTRON_GAPS.md.
 */
export function routeNeedsServerData(route: RouteInfo, chain: RouteInfo[]): boolean {
  for (const entry of [...chain, route]) {
    if (entry.mode !== "static") return true;
    if (entry.hasLoader !== false) return true;
  }
  return false;
}

async function ensureRouteChainModules(chain: RouteInfo[]): Promise<void> {
  await Promise.all(chain.map((route) => ensureRouteModule(route)));
}

async function ensureRouteModule(route: RouteInfo): Promise<RouteModule> {
  if (route.module) {
    return route.module;
  }

  const loaded = await route.load();
  route.module = loaded;
  return loaded;
}

function normalizeRouteModule(value: unknown): RouteModule {
  const module = value as RouteModule;
  if (!module || typeof module.default !== "function") {
    throw new Error("Invalid route module: missing default export.");
  }
  return module;
}
